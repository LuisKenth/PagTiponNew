"use client";

/** Generates a selectable-text, multi-page A4 landscape PDF. No screenshot/HTML canvas needed. */
export type PdfReportOptions = {
  title: string;
  subtitle?: string;
  details?: Array<[string, string]>;
  metrics: Array<[string, string]>;
  headers: string[];
  rows: string[][];
  filename: string;
  note?: string;
};

const readable = (value: string | null | undefined) => String(value ?? "")
  .replace(/[\u2013\u2014]/g, "-")
  .replace(/[\u2018\u2019]/g, "'")
  .replace(/[\u201c\u201d]/g, '"')
  .replace(/[\u2022]/g, "-")
  .replace(/[\u0000-\u001f\u007f]/g, " ")
  .trim();

export async function exportReportPdf(options: PdfReportOptions): Promise<void> {
  const { jsPDF } = await import("jspdf");
  const doc = new jsPDF({ orientation: "landscape", unit: "mm", format: "a4" });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 13;
  const usable = pageWidth - margin * 2;
  const bottom = pageHeight - 16;
  const headingBlue: [number, number, number] = [18, 37, 76];
  const accent: [number, number, number] = [79, 70, 229];
  const smallText: [number, number, number] = [71, 85, 105];
  let y = margin;

  function topBar() {
    doc.setFillColor(...headingBlue);
    doc.rect(0, 0, pageWidth, 16, "F");
    doc.setFont("helvetica", "bold");
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(11);
    doc.text("PAGTIPON  |  PROVINCE OF ANTIQUE", margin, 10.5);
    y = 22;
  }
  function pageFooter() {
    const pages = doc.getNumberOfPages();
    for (let i = 1; i <= pages; i++) {
      doc.setPage(i);
      doc.setDrawColor(226, 232, 240);
      doc.line(margin, pageHeight - 12, pageWidth - margin, pageHeight - 12);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(8);
      doc.setTextColor(...smallText);
      doc.text("Generated by PagTipon  |  All times in Philippine Standard Time", margin, pageHeight - 7);
      doc.text(`Page ${i} of ${pages}`, pageWidth - margin, pageHeight - 7, { align: "right" });
    }
  }
  function addPage() {
    doc.addPage();
    topBar();
  }
  function line(label: string, value: string) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.setTextColor(...smallText);
    doc.text(readable(label), margin, y);
    doc.setFont("helvetica", "normal");
    doc.setTextColor(15, 23, 42);
    const lines = doc.splitTextToSize(readable(value), usable - 43) as string[];
    doc.text(lines, margin + 43, y);
    y += Math.max(1, lines.length) * 4.7;
  }
  topBar();
  doc.setFont("helvetica", "bold");
  doc.setTextColor(...headingBlue);
  doc.setFontSize(17);
  const headings = doc.splitTextToSize(readable(options.title), usable) as string[];
  doc.text(headings, margin, y + 3);
  y += 8 + (headings.length - 1) * 6;
  if (options.subtitle) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(...smallText);
    const parts = doc.splitTextToSize(readable(options.subtitle), usable) as string[];
    doc.text(parts, margin, y);
    y += parts.length * 4.5 + 2;
  }
  y += 2;
  if (options.details?.length) {
    for (const [label, value] of options.details) {
      if (y > bottom - 18) addPage();
      line(label, value);
    }
    y += 3;
  }
  const cardGap = 3;
  const metrics = options.metrics.slice(0, 6);
  if (metrics.length) {
    const cardWidth = (usable - cardGap * (metrics.length - 1)) / metrics.length;
    if (y + 18 > bottom) addPage();
    for (let i = 0; i < metrics.length; i++) {
      const x = margin + i * (cardWidth + cardGap);
      doc.setFillColor(239, 242, 255);
      doc.roundedRect(x, y, cardWidth, 18, 1.7, 1.7, "F");
      doc.setFont("helvetica", "bold");
      doc.setFontSize(7.5);
      doc.setTextColor(...smallText);
      const labels = doc.splitTextToSize(readable(metrics[i][0]), cardWidth - 5) as string[];
      doc.text(labels.slice(0, 2), x + 2.5, y + 5.5);
      doc.setFontSize(13);
      doc.setTextColor(...headingBlue);
      doc.text(readable(metrics[i][1]), x + 2.5, y + 14.5);
    }
    y += 24;
  }
  if (options.note) {
    doc.setFont("helvetica", "italic");
    doc.setFontSize(8);
    doc.setTextColor(...smallText);
    const lines = doc.splitTextToSize(readable(options.note), usable) as string[];
    if (y + lines.length * 4 > bottom - 12) addPage();
    doc.text(lines, margin, y);
    y += lines.length * 4 + 5;
  }
  const n = options.headers.length;
  if (!n) {
    pageFooter();
    doc.save(options.filename);
    return;
  }
  // Give first and second columns a little extra room for event and participant names.
  const weights = options.headers.map((_, index) => (index === 0 ? 2 : index === 1 ? 1.45 : 1));
  const weightTotal = weights.reduce((a, b) => a + b, 0);
  const widths = weights.map((weight) => usable * weight / weightTotal);
  const headerHeight = 11;
  const textSize = n >= 8 ? 7.2 : 8;

  function header() {
    if (y + headerHeight + 7 > bottom) addPage();
    doc.setFillColor(...accent);
    doc.rect(margin, y, usable, headerHeight, "F");
    let x = margin;
    for (let index = 0; index < n; index++) {
      doc.setFont("helvetica", "bold");
      doc.setTextColor(255, 255, 255);
      doc.setFontSize(7.3);
      const text = doc.splitTextToSize(readable(options.headers[index]), widths[index] - 3) as string[];
      doc.text(text.slice(0, 3), x + 1.5, y + 4.4);
      x += widths[index];
    }
    y += headerHeight;
  }
  header();
  const shownRows = options.rows.length ? options.rows : [["No records for the selected filters.", ...Array(n - 1).fill("")]];
  shownRows.forEach((row, idx) => {
    const texts = options.headers.map((_, i) => {
      doc.setFont("helvetica", "normal");
      doc.setFontSize(textSize);
      const lines = doc.splitTextToSize(readable(row[i] ?? ""), widths[i] - 3) as string[];
      return lines.length > 6 ? [...lines.slice(0, 5), `${lines[5].slice(0, 18)}...`] : lines;
    });
    const rowHeight = Math.max(7.5, ...texts.map((t) => t.length * 3.6 + 3));
    if (y + rowHeight > bottom) { addPage(); header(); }
    if (idx % 2 === 0) {
      doc.setFillColor(248, 250, 252);
      doc.rect(margin, y, usable, rowHeight, "F");
    }
    doc.setDrawColor(226, 232, 240);
    doc.line(margin, y + rowHeight, pageWidth - margin, y + rowHeight);
    let x = margin;
    for (let i = 0; i < n; i++) {
      doc.setTextColor(30, 41, 59);
      doc.setFont("helvetica", "normal");
      doc.setFontSize(textSize);
      doc.text(texts[i], x + 1.5, y + 4.3);
      x += widths[i];
    }
    y += rowHeight;
  });
  pageFooter();
  doc.save(options.filename);
}
